-- Canonical schema for new installations.
-- Existing username-based installations must run
-- admin_users_email_login_migration.sql instead of rerunning this file.

create table if not exists public.admin_users (
  id bigint generated by default as identity primary key,
  email text not null,
  password_hash text not null,
  is_active boolean not null default true,
  created_at timestamptz not null default timezone('utc', now()),
  updated_at timestamptz not null default timezone('utc', now()),
  constraint admin_users_email_key unique (email),
  constraint admin_users_email_normalized_check
    check (email = lower(btrim(email))),
  constraint admin_users_email_format_check
    check (
      char_length(email) between 3 and 254
      and email ~ '^[a-z0-9!#$%&''*+/=?^_`{|}~-]+(\.[a-z0-9!#$%&''*+/=?^_`{|}~-]+)*@[a-z0-9]([a-z0-9-]{0,61}[a-z0-9])?(\.[a-z0-9]([a-z0-9-]{0,61}[a-z0-9])?)+$'
    )
);

create or replace function public.set_current_timestamp_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = timezone('utc', now());
  return new;
end;
$$;

drop trigger if exists set_admin_users_updated_at on public.admin_users;
create trigger set_admin_users_updated_at
before update on public.admin_users
for each row execute function public.set_current_timestamp_updated_at();
