create table if not exists public.community_highlights (
  id bigint generated by default as identity primary key,
  title text not null,
  slug text not null unique,
  category text not null check (category in ('Education Program', 'Community Activity', 'Public Advisory')),
  event_date date not null,
  short_description text not null,
  long_description text not null,
  image_filename text,
  is_published boolean not null default true,
  created_at timestamptz not null default timezone('utc', now()),
  updated_at timestamptz not null default timezone('utc', now())
);

create table if not exists public.community_events (
  id bigint generated by default as identity primary key,
  title text not null,
  slug text not null unique,
  event_date date not null,
  short_description text not null,
  long_description text not null,
  image_filename text,
  is_published boolean not null default true,
  created_at timestamptz not null default timezone('utc', now()),
  updated_at timestamptz not null default timezone('utc', now())
);

create or replace function public.set_current_timestamp_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = timezone('utc', now());
  return new;
end;
$$;

drop trigger if exists set_community_highlights_updated_at on public.community_highlights;
create trigger set_community_highlights_updated_at
before update on public.community_highlights
for each row execute function public.set_current_timestamp_updated_at();

drop trigger if exists set_community_events_updated_at on public.community_events;
create trigger set_community_events_updated_at
before update on public.community_events
for each row execute function public.set_current_timestamp_updated_at();

