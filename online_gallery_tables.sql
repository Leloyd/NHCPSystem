create table if not exists public.online_gallery_categories (
  id bigint generated by default as identity primary key,
  slug text not null unique,
  display_name text not null unique,
  sort_order integer not null default 0,
  is_active boolean not null default true,
  created_at timestamptz not null default timezone('utc', now()),
  updated_at timestamptz not null default timezone('utc', now())
);

create table if not exists public.online_gallery_items (
  id bigint generated by default as identity primary key,
  category_id bigint not null references public.online_gallery_categories(id) on delete restrict,
  title text not null,
  title_tl text,
  period text,
  year_label text,
  source text,
  location text,
  location_tl text,
  short_caption text not null,
  short_caption_tl text,
  full_description text not null,
  full_description_tl text,
  teaching_note text,
  tags jsonb not null default '[]'::jsonb,
  image_filename text,
  is_published boolean not null default true,
  sort_order integer not null default 0,
  created_at timestamptz not null default timezone('utc', now()),
  updated_at timestamptz not null default timezone('utc', now())
);

alter table if exists public.online_gallery_items
  add column if not exists title_tl text,
  add column if not exists location_tl text,
  add column if not exists short_caption_tl text,
  add column if not exists full_description_tl text;

alter table if exists public.online_gallery_items alter column period drop not null;
alter table if exists public.online_gallery_items alter column year_label drop not null;
alter table if exists public.online_gallery_items alter column source drop not null;
alter table if exists public.online_gallery_items alter column location drop not null;
alter table if exists public.online_gallery_items alter column teaching_note drop not null;

create or replace function public.set_current_timestamp_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = timezone('utc', now());
  return new;
end;
$$;

drop trigger if exists set_online_gallery_categories_updated_at on public.online_gallery_categories;
create trigger set_online_gallery_categories_updated_at
before update on public.online_gallery_categories
for each row execute function public.set_current_timestamp_updated_at();

drop trigger if exists set_online_gallery_items_updated_at on public.online_gallery_items;
create trigger set_online_gallery_items_updated_at
before update on public.online_gallery_items
for each row execute function public.set_current_timestamp_updated_at();

