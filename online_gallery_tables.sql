create table if not exists public.online_gallery_categories (
  id bigint generated by default as identity primary key,
  slug text not null unique,
  display_name text not null unique,
  sort_order integer not null default 0,
  is_active boolean not null default true,
  created_at timestamptz not null default timezone('utc', now()),
  updated_at timestamptz not null default timezone('utc', now())
);

create table if not exists public.online_gallery_items (
  id bigint generated by default as identity primary key,
  category_id bigint not null references public.online_gallery_categories(id) on delete restrict,
  title text not null,
  period text not null default '',
  year_label text not null default '',
  source text not null default '',
  location text not null default '',
  short_caption text not null,
  full_description text not null,
  teaching_note text not null default '',
  tags jsonb not null default '[]'::jsonb,
  image_filename text,
  is_published boolean not null default true,
  sort_order integer not null default 0,
  created_at timestamptz not null default timezone('utc', now()),
  updated_at timestamptz not null default timezone('utc', now())
);

