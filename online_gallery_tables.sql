create or replace function public.set_current_timestamp_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = timezone('utc', now());
  return new;
end;
$$;

drop trigger if exists set_online_gallery_categories_updated_at on public.online_gallery_categories;
create trigger set_online_gallery_categories_updated_at
before update on public.online_gallery_categories
for each row execute function public.set_current_timestamp_updated_at();

drop trigger if exists set_online_gallery_items_updated_at on public.online_gallery_items;
create trigger set_online_gallery_items_updated_at
before update on public.online_gallery_items
for each row execute function public.set_current_timestamp_updated_at();

