update public.online_gallery_items
set period = coalesce(period, ''),
    year_label = coalesce(year_label, ''),
    source = coalesce(source, ''),
    location = coalesce(location, ''),
    short_caption = coalesce(short_caption, ''),
    full_description = coalesce(full_description, ''),
    teaching_note = coalesce(teaching_note, ''),
    tags = coalesce(tags, '[]'::jsonb),
    is_published = coalesce(is_published, true),
    sort_order = coalesce(sort_order, 0),
    created_at = coalesce(created_at, timezone('utc', now())),
    updated_at = coalesce(updated_at, timezone('utc', now()))
where period is null
   or year_label is null
   or source is null
   or location is null
   or short_caption is null
   or full_description is null
   or teaching_note is null
   or tags is null
   or is_published is null
   or sort_order is null
   or created_at is null
   or updated_at is null;

