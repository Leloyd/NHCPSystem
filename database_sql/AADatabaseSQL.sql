CREATE OR REPLACE FUNCTION public.moderate_visitor_feedback(
  p_feedback_id bigint, p_action text, p_reason_code text DEFAULT '',
  p_note text DEFAULT '', p_admin text DEFAULT ''
) RETURNS void LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE v_feedback public.visitor_feedback%ROWTYPE;
BEGIN
  SELECT * INTO v_feedback FROM public.visitor_feedback WHERE id = p_feedback_id FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'Visitor feedback not found'; END IF;
  IF p_action = 'publish_comment' THEN
    IF NOT v_feedback.public_display_consent OR btrim(v_feedback.comments) = '' OR v_feedback.rating_status = 'excluded' THEN RAISE EXCEPTION 'This comment is not eligible for publication'; END IF;
    UPDATE public.visitor_feedback SET comment_status='published', status='reviewed', moderation_reason_code='', moderation_note='', moderated_at=timezone('utc',now()), moderated_by=p_admin, reviewed_at=timezone('utc',now()), reviewed_by=p_admin WHERE id=p_feedback_id;
  ELSIF p_action = 'withhold_comment' THEN
    IF p_reason_code <> ALL (ARRAY['personal_information','harassment','hate_or_abuse','obscene','advertising','off_topic','spam','other']) OR char_length(btrim(p_note)) < 10 THEN RAISE EXCEPTION 'A valid policy reason and note are required'; END IF;
    UPDATE public.visitor_feedback SET comment_status='withheld', status='reviewed', moderation_reason_code=p_reason_code, moderation_note=btrim(p_note), moderated_at=timezone('utc',now()), moderated_by=p_admin, reviewed_at=timezone('utc',now()), reviewed_by=p_admin WHERE id=p_feedback_id;
  ELSIF p_action = 'exclude_rating' THEN
    IF p_reason_code <> ALL (ARRAY['fraud','duplicate','ineligible','conflict_of_interest','manipulation']) OR char_length(btrim(p_note)) < 10 THEN RAISE EXCEPTION 'A valid eligibility reason and evidence note are required'; END IF;
    UPDATE public.visitor_feedback SET rating_status='excluded', comment_status='withheld', status='reviewed', moderation_reason_code=p_reason_code, moderation_note=btrim(p_note), moderated_at=timezone('utc',now()), moderated_by=p_admin, reviewed_at=timezone('utc',now()), reviewed_by=p_admin WHERE id=p_feedback_id;
  ELSIF p_action = 'reinstate_rating' THEN
    IF v_feedback.rating_status <> 'excluded' THEN RAISE EXCEPTION 'The rating is not excluded'; END IF;
    UPDATE public.visitor_feedback SET rating_status='counted', moderation_reason_code='', moderation_note='', moderated_at=timezone('utc',now()), moderated_by=p_admin, reviewed_at=timezone('utc',now()), reviewed_by=p_admin WHERE id=p_feedback_id;
  ELSE RAISE EXCEPTION 'Unsupported visitor feedback moderation action';
  END IF;
  INSERT INTO public.visitor_feedback_moderation_log (feedback_id, action, reason_code, note, admin_username) VALUES (p_feedback_id,p_action,p_reason_code,btrim(p_note),p_admin);
END;
$$;
