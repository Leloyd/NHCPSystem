CREATE INDEX IF NOT EXISTS admin_login_otp_admin_time_idx ON public.admin_login_otp_challenges (admin_user_id, created_at DESC);
CREATE INDEX IF NOT EXISTS admin_login_otp_ip_time_idx ON public.admin_login_otp_challenges (request_ip_hash, created_at DESC);
