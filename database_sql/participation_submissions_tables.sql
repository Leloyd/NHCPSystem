create table if not exists public.community_participation_submissions (
  id bigint generated by default as identity primary key,
  submission_type text not null check (submission_type in ('teacher_corner', 'story_submit')),
  title text not null,
  resource_category text not null default '',
  story_category text not null default '',
  submitter_name text not null,
  submitter_email text not null,
  subject_topic text not null default '',
  description text not null default '',
  story_content text not null default '',
  resource_file_filename text,
  photo_filename text,
  is_private boolean not null default false,
  status text not null default 'pending_verification' check (status in ('pending_verification', 'pending_review', 'active', 'archived')),
  verification_code_hash text,
  verification_sent_at timestamptz,
  verification_expires_at timestamptz,
  verified_at timestamptz,
  reviewed_at timestamptz,
  reviewed_by text not null default '',
  created_at timestamptz not null default timezone('utc', now()),
  updated_at timestamptz not null default timezone('utc', now())
);

create index if not exists idx_community_participation_submissions_email on public.community_participation_submissions (submitter_email);
create index if not exists idx_community_participation_submissions_status on public.community_participation_submissions (status);

create or replace function public.set_current_timestamp_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = timezone('utc', now());
  return new;
end;
$$;

drop trigger if exists set_community_participation_submissions_updated_at on public.community_participation_submissions;
create trigger set_community_participation_submissions_updated_at
before update on public.community_participation_submissions
for each row execute function public.set_current_timestamp_updated_at();
