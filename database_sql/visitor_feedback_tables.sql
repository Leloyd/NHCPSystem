create table if not exists public.visitor_feedback (
  id bigint generated by default as identity primary key,
  visit_type text not null check (visit_type in ('on-site', 'website')),
  rating integer not null check (rating between 1 and 5),
  visitor_name text not null default '',
  comments text not null default '',
  status text not null default 'new' check (status in ('new', 'reviewed', 'archived')),
  public_display_consent boolean not null default false,
  public_name_preference text not null default 'anonymous' check (public_name_preference in ('anonymous', 'first_name')),
  rating_status text not null default 'counted' check (rating_status in ('counted', 'excluded')),
  comment_status text not null default 'pending' check (comment_status in ('not_provided', 'pending', 'published', 'withheld')),
  moderation_reason_code text not null default '',
  moderation_note text not null default '' check (char_length(moderation_note) <= 2000),
  moderated_at timestamptz,
  moderated_by text not null default '',
  reviewed_at timestamptz,
  reviewed_by text not null default '',
  created_at timestamptz not null default timezone('utc', now()),
  updated_at timestamptz not null default timezone('utc', now())
);

create index if not exists idx_visitor_feedback_status on public.visitor_feedback (status);
comment on column public.visitor_feedback.public_display_consent is
  'Consent to publish the written comment; eligible numerical ratings are public independently.';
create index if not exists idx_visitor_feedback_created_at on public.visitor_feedback (created_at desc);
create index if not exists visitor_feedback_public_summary_idx on public.visitor_feedback (visit_type, rating_status, public_display_consent, created_at desc);
create index if not exists visitor_feedback_comment_queue_idx on public.visitor_feedback (comment_status, created_at desc);

create or replace function public.enforce_visitor_feedback_cooldown()
returns trigger language plpgsql set search_path = public as $$
begin
  if new.user_id is null then return new; end if;
  perform pg_advisory_xact_lock(hashtextextended(new.user_id::text || ':' || new.visit_type, 0));
  if exists (select 1 from public.visitor_feedback where user_id=new.user_id and visit_type=new.visit_type and created_at >= timezone('utc',now()) - interval '30 days') then
    raise exception 'Only one review per experience type is allowed every 30 days';
  end if;
  return new;
end;
$$;
drop trigger if exists enforce_visitor_feedback_cooldown_trigger on public.visitor_feedback;
create trigger enforce_visitor_feedback_cooldown_trigger before insert on public.visitor_feedback for each row execute function public.enforce_visitor_feedback_cooldown();

create table if not exists public.visitor_feedback_moderation_log (
  id bigint generated by default as identity primary key,
  feedback_id bigint not null references public.visitor_feedback(id) on delete cascade,
  action text not null check (action in ('publish_comment', 'withhold_comment', 'exclude_rating', 'reinstate_rating', 'reanalyze')),
  reason_code text not null default '',
  note text not null default '' check (char_length(note) <= 2000),
  admin_username text not null default '',
  created_at timestamptz not null default timezone('utc', now())
);

create index if not exists visitor_feedback_moderation_log_feedback_idx
  on public.visitor_feedback_moderation_log (feedback_id, created_at desc);

create or replace function public.set_current_timestamp_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = timezone('utc', now());
  return new;
end;
$$;

drop trigger if exists set_visitor_feedback_updated_at on public.visitor_feedback;
create trigger set_visitor_feedback_updated_at
before update on public.visitor_feedback
for each row execute function public.set_current_timestamp_updated_at();

alter table public.visitor_feedback enable row level security;
alter table public.visitor_feedback_moderation_log enable row level security;
revoke all on table public.visitor_feedback from public, anon, authenticated;
revoke all on table public.visitor_feedback_moderation_log from public, anon, authenticated;
grant select, insert, update, delete on table public.visitor_feedback to service_role;
grant select, insert on table public.visitor_feedback_moderation_log to service_role;

create or replace function public.moderate_visitor_feedback(
  p_feedback_id bigint, p_action text, p_reason_code text default '',
  p_note text default '', p_admin text default ''
) returns void language plpgsql security definer set search_path = public as $$
declare v_feedback public.visitor_feedback%rowtype;
begin
  select * into v_feedback from public.visitor_feedback where id = p_feedback_id for update;
  if not found then raise exception 'Visitor feedback not found'; end if;
  if p_action = 'publish_comment' then
    if not v_feedback.public_display_consent or btrim(v_feedback.comments) = '' or v_feedback.rating_status = 'excluded' then raise exception 'This comment is not eligible for publication'; end if;
    update public.visitor_feedback set comment_status='published',status='reviewed',moderation_reason_code='',moderation_note='',moderated_at=timezone('utc',now()),moderated_by=p_admin,reviewed_at=timezone('utc',now()),reviewed_by=p_admin where id=p_feedback_id;
  elsif p_action = 'withhold_comment' then
    if p_reason_code <> all(array['personal_information','harassment','hate_or_abuse','obscene','advertising','off_topic','spam','other']) or char_length(btrim(p_note)) < 10 then raise exception 'A valid policy reason and note are required'; end if;
    update public.visitor_feedback set comment_status='withheld',status='reviewed',moderation_reason_code=p_reason_code,moderation_note=btrim(p_note),moderated_at=timezone('utc',now()),moderated_by=p_admin,reviewed_at=timezone('utc',now()),reviewed_by=p_admin where id=p_feedback_id;
  elsif p_action = 'exclude_rating' then
    if p_reason_code <> all(array['fraud','duplicate','ineligible','conflict_of_interest','manipulation']) or char_length(btrim(p_note)) < 10 then raise exception 'A valid eligibility reason and evidence note are required'; end if;
    update public.visitor_feedback set rating_status='excluded',comment_status='withheld',status='reviewed',moderation_reason_code=p_reason_code,moderation_note=btrim(p_note),moderated_at=timezone('utc',now()),moderated_by=p_admin,reviewed_at=timezone('utc',now()),reviewed_by=p_admin where id=p_feedback_id;
  elsif p_action = 'reinstate_rating' then
    if v_feedback.rating_status <> 'excluded' then raise exception 'The rating is not excluded'; end if;
    update public.visitor_feedback set rating_status='counted',moderation_reason_code='',moderation_note='',moderated_at=timezone('utc',now()),moderated_by=p_admin,reviewed_at=timezone('utc',now()),reviewed_by=p_admin where id=p_feedback_id;
  else raise exception 'Unsupported visitor feedback moderation action';
  end if;
  insert into public.visitor_feedback_moderation_log(feedback_id,action,reason_code,note,admin_username) values(p_feedback_id,p_action,p_reason_code,btrim(p_note),p_admin);
end;
$$;
revoke all on function public.moderate_visitor_feedback(bigint,text,text,text,text) from public, anon, authenticated;
grant execute on function public.moderate_visitor_feedback(bigint,text,text,text,text) to service_role;
revoke all on function public.enforce_visitor_feedback_cooldown() from public, anon, authenticated;
