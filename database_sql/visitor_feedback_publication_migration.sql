-- Fair public visitor-feedback publication.
-- Ratings and written comments have separate moderation states so every
-- eligible rating is public even when its comment is not published.
-- Safe to run more than once.

BEGIN;

ALTER TABLE public.visitor_feedback
  ADD COLUMN IF NOT EXISTS public_display_consent boolean NOT NULL DEFAULT false,
  ADD COLUMN IF NOT EXISTS public_name_preference text NOT NULL DEFAULT 'anonymous',
  ADD COLUMN IF NOT EXISTS rating_status text NOT NULL DEFAULT 'counted',
  ADD COLUMN IF NOT EXISTS comment_status text NOT NULL DEFAULT 'pending',
  ADD COLUMN IF NOT EXISTS moderation_reason_code text NOT NULL DEFAULT '',
  ADD COLUMN IF NOT EXISTS moderation_note text NOT NULL DEFAULT '',
  ADD COLUMN IF NOT EXISTS moderated_at timestamp with time zone,
  ADD COLUMN IF NOT EXISTS moderated_by text NOT NULL DEFAULT '';

COMMENT ON COLUMN public.visitor_feedback.public_display_consent IS
  'Consent to publish the written comment; eligible numerical ratings are public independently.';

ALTER TABLE public.visitor_feedback
  DROP CONSTRAINT IF EXISTS visitor_feedback_public_name_preference_check,
  DROP CONSTRAINT IF EXISTS visitor_feedback_rating_status_check,
  DROP CONSTRAINT IF EXISTS visitor_feedback_comment_status_check,
  DROP CONSTRAINT IF EXISTS visitor_feedback_moderation_note_check;

ALTER TABLE public.visitor_feedback
  ADD CONSTRAINT visitor_feedback_public_name_preference_check
    CHECK (public_name_preference IN ('anonymous', 'first_name')),
  ADD CONSTRAINT visitor_feedback_rating_status_check
    CHECK (rating_status IN ('counted', 'excluded')),
  ADD CONSTRAINT visitor_feedback_comment_status_check
    CHECK (comment_status IN ('not_provided', 'pending', 'published', 'withheld')),
  ADD CONSTRAINT visitor_feedback_moderation_note_check
    CHECK (char_length(moderation_note) <= 2000);

-- Existing responses did not include informed consent to publish their
-- comments. Their eligible ratings may still enter the aggregate, while their
-- written comments remain private.
UPDATE public.visitor_feedback
SET comment_status = CASE WHEN btrim(comments) = '' THEN 'not_provided' ELSE 'withheld' END
WHERE public_display_consent = false;

CREATE INDEX IF NOT EXISTS visitor_feedback_public_summary_idx
  ON public.visitor_feedback (visit_type, rating_status, public_display_consent, created_at DESC);
CREATE INDEX IF NOT EXISTS visitor_feedback_comment_queue_idx
  ON public.visitor_feedback (comment_status, created_at DESC);

CREATE OR REPLACE FUNCTION public.enforce_visitor_feedback_cooldown()
RETURNS trigger LANGUAGE plpgsql SET search_path = public AS $$
BEGIN
  IF NEW.user_id IS NULL THEN RETURN NEW; END IF;
  PERFORM pg_advisory_xact_lock(hashtextextended(NEW.user_id::text || ':' || NEW.visit_type, 0));
  IF EXISTS (
    SELECT 1 FROM public.visitor_feedback
    WHERE user_id = NEW.user_id AND visit_type = NEW.visit_type
      AND created_at >= timezone('utc', now()) - interval '30 days'
  ) THEN
    RAISE EXCEPTION 'Only one review per experience type is allowed every 30 days';
  END IF;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS enforce_visitor_feedback_cooldown_trigger ON public.visitor_feedback;
CREATE TRIGGER enforce_visitor_feedback_cooldown_trigger
BEFORE INSERT ON public.visitor_feedback
FOR EACH ROW EXECUTE FUNCTION public.enforce_visitor_feedback_cooldown();

CREATE TABLE IF NOT EXISTS public.visitor_feedback_moderation_log (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  feedback_id bigint NOT NULL REFERENCES public.visitor_feedback(id) ON DELETE CASCADE,
  action text NOT NULL CHECK (action IN (
    'publish_comment', 'withhold_comment', 'exclude_rating',
    'reinstate_rating', 'reanalyze'
  )),
  reason_code text NOT NULL DEFAULT '',
  note text NOT NULL DEFAULT '' CHECK (char_length(note) <= 2000),
  admin_username text NOT NULL DEFAULT '',
  created_at timestamp with time zone NOT NULL DEFAULT timezone('utc', now())
);

CREATE INDEX IF NOT EXISTS visitor_feedback_moderation_log_feedback_idx
  ON public.visitor_feedback_moderation_log (feedback_id, created_at DESC);

-- All browser access goes through authenticated Flask routes. The service-role
-- key must remain server-only; there are deliberately no public RLS policies.
ALTER TABLE public.visitor_feedback ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.visitor_feedback_moderation_log ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.visitor_feedback FROM PUBLIC, anon, authenticated;
REVOKE ALL ON TABLE public.visitor_feedback_moderation_log FROM PUBLIC, anon, authenticated;
GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE public.visitor_feedback TO service_role;
GRANT SELECT, INSERT ON TABLE public.visitor_feedback_moderation_log TO service_role;

-- Apply publication decisions and their audit row in one transaction. Direct
-- browser roles cannot call this function.
CREATE OR REPLACE FUNCTION public.moderate_visitor_feedback(
  p_feedback_id bigint,
  p_action text,
  p_reason_code text DEFAULT '',
  p_note text DEFAULT '',
  p_admin text DEFAULT ''
)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_feedback public.visitor_feedback%ROWTYPE;
BEGIN
  SELECT * INTO v_feedback FROM public.visitor_feedback WHERE id = p_feedback_id FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'Visitor feedback not found'; END IF;

  IF p_action = 'publish_comment' THEN
    IF NOT v_feedback.public_display_consent OR btrim(v_feedback.comments) = '' OR v_feedback.rating_status = 'excluded' THEN
      RAISE EXCEPTION 'This comment is not eligible for publication';
    END IF;
    UPDATE public.visitor_feedback SET comment_status = 'published', status = 'reviewed',
      moderation_reason_code = '', moderation_note = '', moderated_at = timezone('utc', now()),
      moderated_by = p_admin, reviewed_at = timezone('utc', now()), reviewed_by = p_admin
      WHERE id = p_feedback_id;
  ELSIF p_action = 'withhold_comment' THEN
    IF p_reason_code <> ALL (ARRAY['personal_information','harassment','hate_or_abuse','obscene','advertising','off_topic','spam','other'])
       OR char_length(btrim(p_note)) < 10 THEN RAISE EXCEPTION 'A valid policy reason and note are required'; END IF;
    UPDATE public.visitor_feedback SET comment_status = 'withheld', status = 'reviewed',
      moderation_reason_code = p_reason_code, moderation_note = btrim(p_note), moderated_at = timezone('utc', now()),
      moderated_by = p_admin, reviewed_at = timezone('utc', now()), reviewed_by = p_admin
      WHERE id = p_feedback_id;
  ELSIF p_action = 'exclude_rating' THEN
    IF p_reason_code <> ALL (ARRAY['fraud','duplicate','ineligible','conflict_of_interest','manipulation'])
       OR char_length(btrim(p_note)) < 10 THEN RAISE EXCEPTION 'A valid eligibility reason and evidence note are required'; END IF;
    UPDATE public.visitor_feedback SET rating_status = 'excluded', comment_status = 'withheld', status = 'reviewed',
      moderation_reason_code = p_reason_code, moderation_note = btrim(p_note), moderated_at = timezone('utc', now()),
      moderated_by = p_admin, reviewed_at = timezone('utc', now()), reviewed_by = p_admin
      WHERE id = p_feedback_id;
  ELSIF p_action = 'reinstate_rating' THEN
    IF v_feedback.rating_status <> 'excluded' THEN RAISE EXCEPTION 'The rating is not excluded'; END IF;
    UPDATE public.visitor_feedback SET rating_status = 'counted', moderation_reason_code = '', moderation_note = '',
      moderated_at = timezone('utc', now()), moderated_by = p_admin,
      reviewed_at = timezone('utc', now()), reviewed_by = p_admin WHERE id = p_feedback_id;
  ELSE
    RAISE EXCEPTION 'Unsupported visitor feedback moderation action';
  END IF;

  INSERT INTO public.visitor_feedback_moderation_log
    (feedback_id, action, reason_code, note, admin_username)
  VALUES (p_feedback_id, p_action, p_reason_code, btrim(p_note), p_admin);
END;
$$;

REVOKE ALL ON FUNCTION public.moderate_visitor_feedback(bigint, text, text, text, text) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.moderate_visitor_feedback(bigint, text, text, text, text) TO service_role;
REVOKE ALL ON FUNCTION public.enforce_visitor_feedback_cooldown() FROM PUBLIC, anon, authenticated;

COMMIT;
