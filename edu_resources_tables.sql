create table if not exists public.edu_resources (
  id bigint generated by default as identity primary key,
  title text not null,
  slug text not null unique,
  category text not null check (category in ('PPT', 'Story', 'DOCS', 'PDF')),
  educator_name text not null default '',
  subject_topic text not null default '',
  author text not null default '',
  year_label text not null default '',
  description text not null,
  file_filename text,
  cover_image_filename text,
  status text not null default 'draft' check (status in ('active', 'draft', 'archived')),
  is_published boolean not null default false,
  created_at timestamptz not null default timezone('utc', now()),
  updated_at timestamptz not null default timezone('utc', now())
);

create or replace function public.set_current_timestamp_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = timezone('utc', now());
  return new;
end;
$$;

drop trigger if exists set_edu_resources_updated_at on public.edu_resources;
create trigger set_edu_resources_updated_at
before update on public.edu_resources
for each row execute function public.set_current_timestamp_updated_at();

