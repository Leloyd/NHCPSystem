create table if not exists public.visitor_feedback (
  id bigint generated by default as identity primary key,
  visit_type text not null check (visit_type in ('on-site', 'website')),
  rating integer not null check (rating between 1 and 5),
  visitor_name text not null default '',
  comments text not null default '',
  status text not null default 'new' check (status in ('new', 'reviewed', 'archived')),
  reviewed_at timestamptz,
  reviewed_by text not null default '',
  created_at timestamptz not null default timezone('utc', now()),
  updated_at timestamptz not null default timezone('utc', now())
);

create index if not exists idx_visitor_feedback_status on public.visitor_feedback (status);
create index if not exists idx_visitor_feedback_created_at on public.visitor_feedback (created_at desc);

create or replace function public.set_current_timestamp_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = timezone('utc', now());
  return new;
end;
$$;

drop trigger if exists set_visitor_feedback_updated_at on public.visitor_feedback;
create trigger set_visitor_feedback_updated_at
before update on public.visitor_feedback
for each row execute function public.set_current_timestamp_updated_at();
